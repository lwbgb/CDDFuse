class Restormer_Encoder(nn.Module):
    def __init__(self,
                 inp_channels=1,
                 out_channels=1,
                 dim=64,
                 num_blocks=[4, 4],
                 heads=[8, 8, 8],
                 ffn_expansion_factor=2,
                 bias=False,
                 LayerNorm_type='WithBias',
                 ):

        super(Restormer_Encoder, self).__init__()

        self.patch_embed = OverlapPatchEmbed(inp_channels, dim)

        self.encoder_level1 = nn.Sequential(*[TransformerBlock(dim=dim, num_heads=heads[0],
            ffn_expansion_factor=ffn_expansion_factor,
            bias=bias, LayerNorm_type=LayerNorm_type) for i in range(num_blocks[0])])
        self.baseFeature = HybridMambaVisionBlock(
            dim=dim, 
            num_heads=heads[2],
            ffn_expansion_factor=ffn_expansion_factor,
            bias=bias,
            LayerNorm_type=LayerNorm_type
        )      
        self.detailFeature = DetailFeatureExtraction()
             
    def forward(self, inp_img):
        inp_enc_level1 = self.patch_embed(inp_img)
        out_enc_level1 = self.encoder_level1(inp_enc_level1)
        base_feature = self.baseFeature(out_enc_level1)
        detail_feature = self.detailFeature(out_enc_level1)
        return base_feature, detail_feature, out_enc_level1

class Restormer_Decoder(nn.Module):
    def __init__(self,
                 inp_channels=1,
                 out_channels=1,
                 dim=64,
                 num_blocks=[4, 4],
                 heads=[8, 8, 8],
                 ffn_expansion_factor=2,
                 bias=False,
                 LayerNorm_type='WithBias',
                 ):

        super(Restormer_Decoder, self).__init__()

        self.reduce_channel = nn.Conv2d(int(dim*2), int(dim), kernel_size=1, bias=bias)
        self.encoder_level2 = nn.Sequential(*[
                HybridMambaVisionBlock(
                    dim=dim,
                    num_heads=heads[1],
                    ffn_expansion_factor=ffn_expansion_factor,
                    bias=bias,
                    LayerNorm_type=LayerNorm_type,
                )
                for i in range(num_blocks[1])]
        )
        
        self.output = nn.Sequential(
            nn.Conv2d(int(dim), int(dim)//2, kernel_size=3,
                      stride=1, padding=1, bias=bias),
            nn.LeakyReLU(),
            nn.Conv2d(int(dim)//2, out_channels, kernel_size=3,
                      stride=1, padding=1, bias=bias),)
        self.sigmoid = nn.Sigmoid()      
                
    def forward(self, inp_img, base_feature, detail_feature):
        out_enc_level0 = torch.cat((base_feature, detail_feature), dim=1)
        out_enc_level0 = self.reduce_channel(out_enc_level0)
        out_enc_level1 = self.encoder_level2(out_enc_level0)
        if inp_img is not None:
            out_enc_level1 = self.output(out_enc_level1) + inp_img
        else:
            out_enc_level1 = self.output(out_enc_level1)
        return self.sigmoid(out_enc_level1), out_enc_level0
    

# 1. 确保顶部有以下导入（如果 mamba_vision.py 和 net_2.py 在同级目录）
class MambaVisionMixer(nn.Module):
    def __init__(
        self,
        d_model,
        d_state=16,
        d_conv=4,
        expand=2,
        dt_rank="auto",
        dt_min=0.001,
        dt_max=0.1,
        dt_init="random",
        dt_scale=1.0,
        dt_init_floor=1e-4,
        conv_bias=True,
        bias=False,
        use_fast_path=True, 
        layer_idx=None,
        device=None,
        dtype=None,
    ):
        factory_kwargs = {"device": device, "dtype": dtype}
        super().__init__()
        self.d_model = d_model
        self.d_state = d_state
        self.d_conv = d_conv
        self.expand = expand
        self.d_inner = int(self.expand * self.d_model)
        self.dt_rank = math.ceil(self.d_model / 16) if dt_rank == "auto" else dt_rank
        self.use_fast_path = use_fast_path
        self.layer_idx = layer_idx
        self.in_proj = nn.Linear(self.d_model, self.d_inner, bias=bias, **factory_kwargs)    
        self.x_proj = nn.Linear(
            self.d_inner//2, self.dt_rank + self.d_state * 2, bias=False, **factory_kwargs
        )
        self.dt_proj = nn.Linear(self.dt_rank, self.d_inner//2, bias=True, **factory_kwargs)
        dt_init_std = self.dt_rank**-0.5 * dt_scale
        if dt_init == "constant":
            nn.init.constant_(self.dt_proj.weight, dt_init_std)
        elif dt_init == "random":
            nn.init.uniform_(self.dt_proj.weight, -dt_init_std, dt_init_std)
        else:
            raise NotImplementedError
        dt = torch.exp(
            torch.rand(self.d_inner//2, **factory_kwargs) * (math.log(dt_max) - math.log(dt_min))
            + math.log(dt_min)
        ).clamp(min=dt_init_floor)
        inv_dt = dt + torch.log(-torch.expm1(-dt))
        with torch.no_grad():
            self.dt_proj.bias.copy_(inv_dt)
        self.dt_proj.bias._no_reinit = True
        A = repeat(
            torch.arange(1, self.d_state + 1, dtype=torch.float32, device=device),
            "n -> d n",
            d=self.d_inner//2,
        ).contiguous()
        A_log = torch.log(A)
        self.A_log = nn.Parameter(A_log)
        self.A_log._no_weight_decay = True
        self.D = nn.Parameter(torch.ones(self.d_inner//2, device=device))
        self.D._no_weight_decay = True
        self.out_proj = nn.Linear(self.d_inner, self.d_model, bias=bias, **factory_kwargs)
        self.conv1d_x = nn.Conv1d(
            in_channels=self.d_inner//2,
            out_channels=self.d_inner//2,
            bias=conv_bias//2,
            kernel_size=d_conv,
            groups=self.d_inner//2,
            **factory_kwargs,
        )
        self.conv1d_z = nn.Conv1d(
            in_channels=self.d_inner//2,
            out_channels=self.d_inner//2,
            bias=conv_bias//2,
            kernel_size=d_conv,
            groups=self.d_inner//2,
            **factory_kwargs,
        )

    def forward(self, hidden_states):
        """
        hidden_states: (B, L, D)
        Returns: same shape as hidden_states
        """
        _, seqlen, _ = hidden_states.shape
        xz = self.in_proj(hidden_states)
        xz = rearrange(xz, "b l d -> b d l")
        x, z = xz.chunk(2, dim=1)
        A = -torch.exp(self.A_log.float())
        x = F.silu(F.conv1d(input=x, weight=self.conv1d_x.weight, bias=self.conv1d_x.bias, padding='same', groups=self.d_inner//2))
        z = F.silu(F.conv1d(input=z, weight=self.conv1d_z.weight, bias=self.conv1d_z.bias, padding='same', groups=self.d_inner//2))
        x_dbl = self.x_proj(rearrange(x, "b d l -> (b l) d"))
        dt, B, C = torch.split(x_dbl, [self.dt_rank, self.d_state, self.d_state], dim=-1)
        dt = rearrange(self.dt_proj(dt), "(b l) d -> b d l", l=seqlen)
        B = rearrange(B, "(b l) dstate -> b dstate l", l=seqlen).contiguous()
        C = rearrange(C, "(b l) dstate -> b dstate l", l=seqlen).contiguous()
        y = selective_scan_fn(x, 
                              dt, 
                              A, 
                              B, 
                              C, 
                              self.D.float(), 
                              z=None, 
                              delta_bias=self.dt_proj.bias.float(), 
                              delta_softplus=True, 
                              return_last_state=None)
        
        y = torch.cat([y, z], dim=1)
        y = rearrange(y, "b d l -> b l d")
        out = self.out_proj(y)
        return out

# 2. 新增：2D 张量到 1D 序列的 Mamba 空间混合适配器
class SpatialMambaVisionAdapter(nn.Module):
    """
    将 2D 图像张量 (B, C, H, W) 展平并送入 NVIDIA MambaVisionMixer，
    处理完毕后再折叠回 2D 形状，完美适配 CDDFuse 管道。
    """
    def __init__(self, dim):
        super().__init__()
        # 严格采用 mamba_vision.py 中 Block 类的极简配置
        self.mixer = MambaVisionMixer(
            d_model=dim, 
            d_state=8,   # 降低状态维度至 8，极大地节省 5070Ti 的显存
            d_conv=3,    # 局部卷积核大小
            expand=1     # 内部不膨胀，保持 C 维度，专为非 Transformer 块设计[cite: 11]
        )
        
    def forward(self, x: torch.Tensor) -> torch.Tensor:
        B, C, H, W = x.shape
        # 维度转换: (B, C, H, W) -> (B, C, L) -> (B, L, D) 这里的 D 即为 C
        x_flat = x.view(B, C, -1).transpose(1, 2) 
        
        # 调用官方 MambaVisionMixer 进行全局空间扫描
        out_flat: torch.Tensor = self.mixer(x_flat)
        
        # 维度逆转换: (B, L, D) -> (B, D, L) -> (B, C, H, W)
        out = out_flat.transpose(1, 2).view(B, C, H, W)
        return out


# 3. 替换原有的 BaseFeatureExtraction
class HybridMambaVisionBlock(nn.Module):
    """
    终极混合模块：官方 MambaVisionMixer (空间) + CDDFuse MDTA (通道) + GDFN
    """
    def __init__(self, dim, num_heads, ffn_expansion_factor=2., bias=False, LayerNorm_type='WithBias'):
        super(HybridMambaVisionBlock, self).__init__()
        
        # 1. 空间域建模 (调用封装好的 NVIDIA MambaVisionMixer)
        self.norm1 = LayerNorm(dim, LayerNorm_type)
        self.spatial_mixer = SpatialMambaVisionAdapter(dim)
        
        # 2. 通道域特征提纯 (使用 CDDFuse 源码中的 Attention 即 MDTA)
        self.norm2 = LayerNorm(dim, LayerNorm_type)
        self.channel_attn = Attention(dim, num_heads, bias) 
        
        # 3. 门控前馈网络 (CDDFuse 原生 GDFN)
        self.norm3 = LayerNorm(dim, LayerNorm_type)
        self.ffn = FeedForward(dim, ffn_expansion_factor, bias)

    def forward(self, x):
        # 严格残差结构，每一步均保持 (B, C, H, W)
        x = x + self.spatial_mixer(self.norm1(x))
        x = x + self.channel_attn(self.norm2(x))
        x = x + self.ffn(self.norm3(x))
        return x


class MIMOHybridMambaVisionFusion(nn.Module):
    """
    Phase II 专用融合层：通道拼接 + 混合 Mamba 空间/通道交织
    """
    def __init__(self, in_dim=128, out_dim=64, num_heads=8):    
        super().__init__()
        # 1. 降维路由
        self.input_proj = nn.Conv2d(in_dim, out_dim, kernel_size=1, bias=False)
        self.act = nn.SiLU()
        
        # 2. 跨模态特征深度交织
        self.hybrid_block = HybridMambaVisionBlock(
            dim=out_dim, 
            num_heads=num_heads
        )

    def forward(self, x_ir, x_vis):
        # 抛弃相加，通道级拼接保留双方独立信息
        x_concat = torch.cat([x_ir, x_vis], dim=1)
        x = self.input_proj(x_concat)
        x = self.act(x)
        
        # 送入 MambaVision Mixer 进行全局扫描融合
        out = self.hybrid_block(x)
        return out